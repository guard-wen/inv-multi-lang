const elements = {
  title: document.querySelector("#manual-title"),
  headingNote: document.querySelector("#heading-note"),
  selector: document.querySelector("#language-select"),
  label: document.querySelector("#language-label"),
  hint: document.querySelector(".language-label-group small"),
  code: document.querySelector("#language-code"),
  caption: document.querySelector("#figure-caption"),
  edition: document.querySelector("#cover-edition"),
  placeholderTitle: document.querySelector("#placeholder-title"),
  placeholderHint: document.querySelector("#placeholder-hint"),
  imageTrigger: document.querySelector("#manual-image-trigger"),
  image: document.querySelector("#manual-image"),
  placeholder: document.querySelector("#image-placeholder"),
  imageViewer: document.querySelector("#image-viewer"),
  imageViewerTitle: document.querySelector("#image-viewer-title"),
  imageViewerImage: document.querySelector("#image-viewer-image"),
  imageViewerClose: document.querySelector("#image-viewer-close")
};

let imageRequest = 0;

function selectedLanguage() {
  const requested = new URLSearchParams(window.location.search).get("lang");
  return manuals[requested] ? requested : "en";
}

function updateLanguage(language, updateUrl = true) {
  const manual = manuals[language];
  if (!manual) return;

  document.documentElement.lang = manual.htmlLang;
  elements.title.innerHTML = manual.title;
  elements.headingNote.textContent = manual.headingNote;
  document.title = `${manual.title.replace("<br>", " ")} | POFET`;
  elements.selector.value = language;
  elements.label.textContent = manual.selectorLabel;
  elements.hint.textContent = manual.selectorHint;
  elements.code.textContent = manual.code;
  elements.caption.textContent = manual.caption;
  elements.edition.textContent = manual.edition;
  elements.placeholderTitle.textContent = manual.placeholderTitle;
  elements.placeholderHint.textContent = manual.placeholderHint;
  elements.placeholder.lang = manual.htmlLang;
  elements.image.alt = manual.caption;
  elements.imageTrigger.setAttribute("aria-label", `Open ${manual.caption} full screen`);

  if (updateUrl) {
    const url = new URL(window.location.href);
    url.searchParams.set("lang", language);
    window.history.replaceState({}, "", url);
  }

  imageRequest += 1;
  const requestId = imageRequest;
  elements.imageTrigger.hidden = true;
  elements.image.removeAttribute("src");
  elements.placeholder.hidden = false;

  const image = new Image();
  image.addEventListener("load", () => {
    if (requestId !== imageRequest) return;
    elements.image.src = manual.image;
    elements.imageTrigger.hidden = false;
    elements.placeholder.hidden = true;
  });
  image.src = manual.image;
}

function openImageViewer() {
  if (!elements.image.getAttribute("src") || elements.imageTrigger.hidden) return;
  elements.imageViewerTitle.textContent = elements.caption.textContent;
  elements.imageViewerImage.src = elements.image.src;
  elements.imageViewerImage.alt = elements.image.alt;
  if (typeof elements.imageViewer.showModal === "function") {
    elements.imageViewer.showModal();
  } else {
    elements.imageViewer.setAttribute("open", "");
  }
}

function closeImageViewer() {
  elements.imageViewer.close();
}

elements.selector.addEventListener("change", () => {
  updateLanguage(elements.selector.value);
});

elements.imageTrigger.addEventListener("click", openImageViewer);
elements.imageViewerClose.addEventListener("click", closeImageViewer);
elements.imageViewer.addEventListener("click", (event) => {
  if (event.target === elements.imageViewer) closeImageViewer();
});

updateLanguage(selectedLanguage(), false);
